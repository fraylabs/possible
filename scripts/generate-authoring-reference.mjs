import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname } from "node:path";
import { fileURLToPath } from "node:url";

const repository = new URL("../", import.meta.url);
const schema = JSON.parse(await readFile(new URL("packages/packs/src/outcome-pack.schema.json", repository), "utf8"));
const target = new URL("skills/possible/references/authoring-fields.md", repository);
const check = process.argv.includes("--check");

const section = (title, properties, required = []) => [
  `## ${title}`,
  "",
  ...Object.entries(properties).flatMap(([name, property]) => [
    `- \`${name}\`${required.includes(name) ? " (required)" : ""} — ${property.description ?? "No description."}`,
    "",
  ]),
];

const output = [
  "# Outcome Pack authoring fields",
  "",
  "Generated from `packages/packs/src/outcome-pack.schema.json`. Do not edit this file by hand.",
  "",
  "The JSON Schema owns the complete authoring surface. Identity, release, source, trust, evidence, discovery fixtures, and showcase media live outside `pack.json`.",
  "",
  ...section("Pack", schema.properties, schema.required),
  ...section("Skill", schema.$defs.skill.properties, schema.$defs.skill.required),
].join("\n").trimEnd() + "\n";

if (check) {
  const current = await readFile(target, "utf8").catch(() => undefined);
  if (current !== output) throw new Error("Generated authoring reference is stale. Run npm run contract:generate.");
} else {
  await mkdir(dirname(fileURLToPath(target)), { recursive: true });
  await writeFile(target, output, "utf8");
  console.log("Generated the Outcome Pack authoring field reference.");
}

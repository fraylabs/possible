import { compilePack, publicCatalog } from "../packages/packs/dist/index.js";

const bulletList = (values) => values.map((value) => `  - ${value}`).join("\n");

const originLines = (entry) => {
  return [
    `- Origin: \`${entry.origin.kind}\``,
    `- Source: ${entry.sourceRecord.source}`,
    `- Revision: \`${entry.sourceRecord.revision}\``,
    `- Manifest path: \`${entry.sourceRecord.path}\``,
    `- Content hash: \`${entry.sourceRecord.contentHash}\``,
    `- Accepted snapshot: \`${entry.snapshotRef}\``,
  ];
};

const evidenceLines = (entry) => {
  if (entry.trust.evidence.length === 0) return ["- Accepted evidence: none"];
  return [
    `- Accepted evidence: ${entry.trust.evidence.length}`,
    ...entry.trust.evidence.map((evidence) => `  - ${evidence.kind}: ${evidence.summary} (${evidence.uri}, \`${evidence.contentHash}\`)`),
  ];
};

const renderEntry = (entry) => {
  const { pack } = entry;
  const requiredExpectations = (pack.expectations ?? []).filter(({ level = "required" }) => level === "required");
  const compiled = pack.lifecycle === "draft" ? undefined : compilePack(pack);
  const publicKey = entry.origin.kind === "bundled" ? pack.slug : entry.id;
  const lines = [
    `## ${pack.name}`,
    "",
    `- Identity: \`${entry.id}\``,
    `- Slug: \`${pack.slug}\``,
    `- Status: \`${entry.trust.status}\``,
    `- Pack version: \`${pack.packVersion}\``,
    `- Public page: https://possible.sh/packs/${publicKey}/`,
    ...originLines(entry),
    ...evidenceLines(entry),
    `- Promise: ${pack.promise}`,
    `- Summary: ${pack.summary}`,
    "- Use when:",
    bulletList(pack.useWhen),
    "- Not for:",
    bulletList(pack.notFor),
    "- Required expectations:",
    bulletList(requiredExpectations.map((expectation) => `${expectation.statement} Evidence: ${expectation.requiredEvidence.join("; ")}`)),
    "- Outputs:",
    bulletList(pack.outputs),
    "- Reviewed Skills:",
    bulletList(pack.skills.map((skill) => `${skill.name} — ${skill.role}; source ${skill.repository}; reviewed revision \`${skill.reviewedRevision}\``)),
  ];
  if (compiled) lines.push("- Install:", "", "```bash", ...compiled.installCommands, "```");
  else lines.push("- Install: unavailable while this community submission remains a listed draft.");
  return lines.join("\n");
};

export function renderPackReference(entries = publicCatalog) {
  const ordered = [...entries].sort((left, right) => left.catalogNumber - right.catalogNumber || left.id.localeCompare(right.id));
  return [
    "<!-- Generated by scripts/sync-pack-reference.mjs. Do not edit by hand. -->",
    "# Outcome Pack catalog",
    "",
    "This is the offline discovery snapshot bundled with `$possible`. Search the live MCP catalog first when `search_packs` is available. Its lexical hints are not semantic ranking. Selection must compare the complete active catalog using each entry's promise, fit, non-scope, expectations, trust status, and accepted evidence; never recommend from its name or search order alone.",
    "",
    "Trust is maintained separately from authorship: `listed` is discoverable but not recommended by default, `experimental` is maintainer-reviewed but insufficiently proven, `verified` has accepted run evidence, and `archived` is historical only.",
    "",
    ...ordered.flatMap((entry, index) => [renderEntry(entry), ...(index === ordered.length - 1 ? [] : [""])]),
    "",
  ].join("\n");
}

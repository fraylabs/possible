import { compilePack, publicCatalog, skillNameFromReference, skillPageUrl } from "../packages/packs/dist/index.js";

const bulletList = (values) => values.map((value) => `  - ${value}`).join("\n");

const originLines = (entry) => [
  `- Origin: \`${entry.origin.kind}\``,
  `- Source: ${entry.sourceRecord.source}`,
  `- Revision: \`${entry.sourceRecord.revision}\``,
  `- Manifest path: \`${entry.sourceRecord.path}\``,
  `- Content hash: \`${entry.sourceRecord.contentHash}\``,
  `- Accepted snapshot: \`${entry.snapshotRef}\``,
];

const evidenceLines = (entry) => entry.trust.evidence.length === 0
  ? ["- Accepted evidence: none"]
  : [
      `- Accepted evidence: ${entry.trust.evidence.length}`,
      ...entry.trust.evidence.map((evidence) => `  - ${evidence.kind}: ${evidence.summary} (${evidence.uri}, \`${evidence.contentHash}\`)`),
    ];

const renderEntry = (entry) => {
  const { pack } = entry;
  const compiled = compilePack(pack);
  const skills = pack.skills ?? [];
  const publicKey = entry.origin.kind === "bundled" ? entry.slug : entry.id;
  return [
    `## ${pack.name}`,
    "",
    `- Identity: \`${entry.id}\``,
    `- Slug: \`${entry.slug}\``,
    `- Status: \`${entry.trust.status}\``,
    `- Public page: https://possible.sh/packs/${publicKey}/`,
    ...originLines(entry),
    ...evidenceLines(entry),
    `- Promise: ${pack.promise}`,
    "- Not for:",
    bulletList(pack.notFor ?? ["No additional selection boundary supplied."]),
    ...(pack.expectations?.length ? ["- Expectations:", bulletList(pack.expectations)] : ["- Expectations: none; the direct prompt contains the finish boundary"]),
    ...(skills.length > 0 ? [
      "- Skills:",
      bulletList(skills.map((skill) => `[${skillNameFromReference(skill)}](${skillPageUrl(skill)}) — ${skill.repository}/${skill.directory}; last reviewed at \`${skill.lastReviewedCommit}\``)),
      "- Install:",
      "",
      "```bash",
      ...compiled.installCommands,
      "```",
    ] : ["- Skills: none required"]),
  ].join("\n");
};

export function renderPackReference(entries = publicCatalog) {
  const ordered = [...entries].sort((left, right) => left.catalogNumber - right.catalogNumber || left.id.localeCompare(right.id));
  return [
    "<!-- Generated by scripts/sync-pack-reference.mjs. Do not edit by hand. -->",
    "# Outcome Pack catalog",
    "",
    "This is the offline discovery snapshot bundled with `$possible`. Search the live MCP catalog first when `search_packs` is available. Compare the complete catalog using each pack's promise, prompt, optional non-scope, expectations, trust status, and accepted evidence; lexical order is only a hint.",
    "",
    "Trust is maintained separately from authorship: `listed` is a valid source submission, `experimental` is maintainer-selected but insufficiently proven, and `verified` has accepted run evidence.",
    "",
    ...ordered.flatMap((entry, index) => [renderEntry(entry), ...(index === ordered.length - 1 ? [] : [""])]),
    "",
  ].join("\n");
}
